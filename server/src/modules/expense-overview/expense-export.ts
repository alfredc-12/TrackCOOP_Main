import { AppError } from "../../utils/app-error";
import type { AuthContext } from "../auth/auth.types";
import { expenseClassLabels } from "./expense-classification";
import { renderReportPdf, renderReportXlsx, type ReportDocument, type ReportSection } from "./expense-report";
import type { ExportKind, ExpenseFilters, ExpenseRecordView, ExpenseSortField } from "./expense-overview.schema";
import type { ExpenseOverviewService } from "./expense-overview.service";

export const exportRowCaps = { xlsx: 100_000, pdf: 5_000 } as const;
const chunkSize = 1000;

const cooperativeName = "Nasugbu Farmers and Fisherfolks Agriculture Cooperative";
const kindTitles: Record<ExportKind, string> = {
  summary: "Operating Expense Summary",
  records: "Expense Records",
  categories: "Category Expense Breakdown",
  comparison: "Expense Period Comparison",
  sources: "Expense Source Breakdown",
  integrity: "Expense Integrity Summary",
};

const definitions: Array<[string, string]> = [
  ["Posted expense", "An Expense ledger record that is Active, has a posting approver (approved_by), and is not itself a reversal entry. Voided, corrected and reversed originals are excluded."],
  ["Operating expense", "Posted expenses whose category is classified as operating. Other recognized expenses, capital expenditure, non-expense disbursements and unclassified rows are reported separately and never added to this figure."],
  ["Reporting date", "financial_records.record_date, read as an Asia/Manila calendar date. An unfinished period is compared with the same number of elapsed days of the earlier period."],
  ["Limitation", "These figures are recorded expenses. The ledger does not record when or how an expense was paid, so they are not confirmed cash outflows. This is not an audited financial statement."],
];

function manilaStamp(date: Date) {
  return new Intl.DateTimeFormat("en-PH", { timeZone: "Asia/Manila", dateStyle: "long", timeStyle: "short" }).format(date);
}

async function describeFilters(service: ExpenseOverviewService, filters: ExpenseFilters, view: ExpenseRecordView) {
  const options = await service.options();
  const names = (ids: string[], source: Array<{ id: string; name: string }>) => ids.map((id) => source.find((item) => item.id === id)?.name ?? `#${id}`).join(", ");
  const lines: string[] = [];
  lines.push(`Classes: ${filters.classes.map((value) => expenseClassLabels[value]).join(", ")}`);
  if (filters.categoryIds.length) lines.push(`Categories: ${names(filters.categoryIds, options.categories)}`);
  if (filters.sourceModules.length) lines.push(`Source modules: ${filters.sourceModules.join(", ")}`);
  if (filters.amountMin !== undefined || filters.amountMax !== undefined) lines.push(`Amount: ${filters.amountMin ?? "any"} to ${filters.amountMax ?? "any"}`);
  if (filters.recordedBy) lines.push(`Recorded by: ${names([filters.recordedBy], options.recordedBy)}`);
  if (filters.postedBy) lines.push(`Posted by: ${names([filters.postedBy], options.postedBy)}`);
  if (filters.seasonId) lines.push(`Season: ${names([filters.seasonId], options.seasons)}`);
  if (filters.search) lines.push(`Search: "${filters.search}"`);
  if (view !== "posted") lines.push(`Record view: ${view}`);
  return lines;
}

export async function buildExpenseReport(
  service: ExpenseOverviewService,
  input: { filters: ExpenseFilters; kind: ExportKind; view: ExpenseRecordView; sortBy: ExpenseSortField; sortDirection: "asc" | "desc"; format: "xlsx" | "pdf" },
  auth: AuthContext,
  now = new Date(),
): Promise<ReportDocument> {
  const { filters, kind, view } = input;
  const plan = service.plan(filters);
  const period = plan.info;
  const meta: Array<[string, string]> = [
    ["Cooperative", cooperativeName],
    ["Report", kindTitles[kind]],
    ["Generated", `${manilaStamp(now)} (Asia/Manila)`],
    ["Generated by", auth.user.displayName],
    ["Reporting period", `${period.label}: ${period.effective.startDate ?? "first record"} to ${period.effective.endDate}${period.effective.partial ? " (period still in progress)" : ""}`],
    ["Comparison", period.previous ? `${period.previous.startDate} to ${period.previous.endDate}` : period.comparisonNote ?? "None"],
    ["Filters", (await describeFilters(service, filters, view)).join("; ")],
    ...definitions,
  ];
  const sections: ReportSection[] = [];

  const needsSummary = kind === "summary";
  if (needsSummary) {
    const summary = await service.summary(filters);
    sections.push({
      title: "Key figures",
      columns: [
        { key: "metric", label: "Metric", kind: "text", weight: 3 },
        { key: "value", label: "Value", kind: "money", weight: 2 },
        { key: "records", label: "Records", kind: "number", weight: 1 },
        { key: "note", label: "Note", kind: "text", weight: 4 },
      ],
      rows: [
        { metric: "Total posted operating expenses", value: summary.totals.amount, records: summary.totals.records, note: `Average per record: ${summary.totals.averageAmount ?? "N/A"}` },
        { metric: "Comparison period total", value: summary.previousTotals?.amount ?? null, records: summary.previousTotals?.records ?? null, note: summary.change.basis === "no_comparison" ? "No comparison selected" : "" },
        { metric: "Change", value: summary.change.amount, records: null, note: summary.change.percent === null ? "Percentage not available (no positive comparison base)" : `${summary.change.percent}%` },
        { metric: "Unposted expense records", value: summary.secondary.unposted.amount, records: summary.secondary.unposted.records, note: "Not in posted totals" },
        { metric: "Voided expense records", value: summary.secondary.voided.amount, records: summary.secondary.voided.records, note: "Audit history; not in posted totals" },
        { metric: "Corrected or reversed", value: summary.secondary.correctedOrReversed.amount, records: summary.secondary.correctedOrReversed.records, note: "Superseded originals; not in posted totals" },
        { metric: "Posted rows needing classification", value: summary.secondary.needsClassification.amount, records: summary.secondary.needsClassification.records, note: "Excluded from the operating total until classified" },
        ...summary.reconciliation.classTotals.map((item) => ({ metric: `Posted - ${expenseClassLabels[item.expenseClass]}`, value: item.amount, records: item.records, note: "All classes, other filters applied" })),
      ],
    });
  }
  if (needsSummary || kind === "categories") {
    const data = await service.categories(filters);
    sections.push({
      title: "Categories",
      columns: [
        { key: "name", label: "Category", kind: "text", weight: 3 },
        { key: "amount", label: "Posted amount", kind: "money" },
        { key: "share", label: "Share", kind: "percent" },
        { key: "records", label: "Records", kind: "number" },
        { key: "previous", label: "Comparison period", kind: "money" },
      ],
      rows: data.items.map((item) => ({ name: item.name, amount: item.amount, share: item.share, records: item.records, previous: item.previousAmount })),
    });
  }
  if (needsSummary || kind === "sources" || kind === "comparison") {
    const data = await service.sources(filters);
    sections.push({
      title: "Source modules",
      columns: [
        { key: "source", label: "Source module", kind: "text", weight: 2 },
        { key: "amount", label: "Posted amount", kind: "money" },
        { key: "share", label: "Share", kind: "percent" },
        { key: "records", label: "Records", kind: "number" },
        { key: "previous", label: "Comparison period", kind: "money" },
        { key: "change", label: "Change", kind: "money" },
      ],
      rows: data.items.map((item) => ({ source: item.sourceModule, amount: item.amount, share: item.share, records: item.records, previous: item.previousAmount, change: item.change })),
    });
  }
  if (needsSummary || kind === "comparison") {
    const drivers = await service.drivers(filters);
    sections.push({
      title: "What changed",
      note: drivers.available ? `Total change ${drivers.totalChange}. Category changes add up to the total change${drivers.reconciles ? "." : " - RECONCILIATION DIFFERENCE, review before use."}` : drivers.unavailableReason ?? "No comparison.",
      columns: [
        { key: "name", label: "Category", kind: "text", weight: 3 },
        { key: "current", label: "Current", kind: "money" },
        { key: "previous", label: "Comparison", kind: "money" },
        { key: "change", label: "Change", kind: "money" },
        { key: "percent", label: "Change %", kind: "percent" },
        { key: "contribution", label: "Share of change", kind: "percent" },
        { key: "state", label: "State", kind: "text" },
      ],
      rows: drivers.items.map((item) => ({ name: item.name, current: item.current, previous: item.previous, change: item.change, percent: item.changePercent, contribution: item.contribution, state: item.state })),
    });
  }
  if (kind === "comparison") {
    const matrix = await service.matrix(filters);
    const names = new Map(matrix.categories.map((item) => [item.categoryId, item.name]));
    sections.push({
      title: "Category by source",
      columns: [
        { key: "category", label: "Category", kind: "text", weight: 3 },
        { key: "source", label: "Source module", kind: "text", weight: 2 },
        { key: "amount", label: "Posted amount", kind: "money" },
        { key: "records", label: "Records", kind: "number" },
        { key: "share", label: "Share", kind: "percent" },
        { key: "previous", label: "Comparison period", kind: "money" },
      ],
      rows: matrix.cells.map((cell) => ({ category: names.get(cell.categoryId) ?? cell.categoryId, source: cell.sourceModule, amount: cell.amount, records: cell.records, share: cell.share, previous: cell.previousAmount })),
    });
  }
  if (needsSummary) {
    const trend = await service.trends(filters);
    sections.push({
      title: "Trend",
      columns: [
        { key: "period", label: "Period", kind: "text", weight: 2 },
        { key: "amount", label: "Posted amount", kind: "money" },
        { key: "records", label: "Records", kind: "number" },
        { key: "top", label: "Largest category", kind: "text", weight: 2 },
        { key: "previous", label: "Comparison period", kind: "money" },
      ],
      rows: trend.buckets.map((bucket) => ({ period: bucket.label, amount: bucket.amount, records: bucket.records, top: bucket.topCategory?.name ?? null, previous: bucket.previous?.amount ?? null })),
    });
  }
  if (needsSummary || kind === "integrity") {
    const data = await service.integrity(filters);
    sections.push({
      title: "Integrity checks",
      columns: [
        { key: "label", label: "Check", kind: "text", weight: 2 },
        { key: "status", label: "Status", kind: "text" },
        { key: "records", label: "Records", kind: "number" },
        { key: "amount", label: "Amount", kind: "money" },
        { key: "description", label: "What it means", kind: "text", weight: 6 },
      ],
      rows: data.checks.map((check) => ({ label: check.label, status: check.status === "review" ? "Requires review" : check.status === "info" ? "For information" : "Clear", records: check.records, amount: check.amount, description: check.description })),
    });
  }
  if (kind === "records") {
    const cap = exportRowCaps[input.format];
    const first = await service.records({ ...filters, view, page: 1, pageSize: 1, sortBy: input.sortBy, sortDirection: input.sortDirection });
    if (first.total > cap) {
      throw new AppError(
        `This export would contain ${first.total.toLocaleString("en-PH")} records, above the ${cap.toLocaleString("en-PH")} limit for ${input.format.toUpperCase()}. Narrow the filters${input.format === "pdf" ? " or choose Excel" : ""}.`,
        413,
        "EXPORT_TOO_LARGE",
      );
    }
    const rows: ReportSection["rows"] = [];
    for (let page = 1; (page - 1) * chunkSize < first.total; page += 1) {
      const chunk = await repositoryPage(service, filters, view, input, page);
      for (const record of chunk) {
        rows.push({
          date: record.recordDate, number: record.recordNumber, category: record.categoryName, classification: expenseClassLabels[record.expenseClass],
          source: record.sourceModule, description: record.description, amount: record.amount, status: record.postingStatus,
          recordedBy: record.recordedBy.name, postedBy: record.postedBy?.name ?? null, season: record.season?.name ?? null,
        });
      }
    }
    sections.push({
      title: "Expense records",
      note: `${first.total} records, total ${first.totalAmount}. Every record matching the filters is included, not one page.`,
      columns: [
        { key: "date", label: "Date", kind: "text" },
        { key: "number", label: "Record no.", kind: "text", weight: 2 },
        { key: "category", label: "Category", kind: "text", weight: 2 },
        { key: "classification", label: "Classification", kind: "text", weight: 2 },
        { key: "source", label: "Source", kind: "text" },
        { key: "description", label: "Description", kind: "text", weight: 4 },
        { key: "amount", label: "Amount", kind: "money", weight: 1.5 },
        { key: "status", label: "Status", kind: "text" },
        { key: "recordedBy", label: "Recorded by", kind: "text", weight: 2 },
        { key: "postedBy", label: "Posted by", kind: "text", weight: 2 },
        { key: "season", label: "Season", kind: "text" },
      ],
      rows,
    });
  }
  return { title: kindTitles[kind], cooperative: cooperativeName, meta, sections };
}

async function repositoryPage(
  service: ExpenseOverviewService,
  filters: ExpenseFilters,
  view: ExpenseRecordView,
  input: { sortBy: ExpenseSortField; sortDirection: "asc" | "desc" },
  page: number,
) {
  const p = service.plan(filters);
  if (!p.effective) return [];
  const result = await service.repository.listRecords(filters, view, { sortBy: input.sortBy, sortDirection: input.sortDirection }, p.effective, page, chunkSize);
  return result.records;
}

export async function exportExpenseReport(
  service: ExpenseOverviewService,
  input: Parameters<typeof buildExpenseReport>[1],
  auth: AuthContext,
  now = new Date(),
) {
  const report = await buildExpenseReport(service, input, auth, now);
  const stamp = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Manila" }).format(now);
  const buffer = input.format === "pdf" ? await renderReportPdf(report) : await renderReportXlsx(report);
  return {
    buffer,
    filename: `trackcoop-expenses-${input.kind}-${stamp}.${input.format}`,
    contentType: input.format === "pdf" ? "application/pdf" : "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  };
}
