export function accessLevelLabel(value: DocumentAccessLevel) {
  return (
    DOCUMENT_ACCESS_LEVELS.find((item) => item.value === value)?.label ?? value
  );
}

export function humanizeConstant(value: string) {
  return value
    .toLowerCase()
    .replaceAll("_", " ")
    .replace(/\b\w/g, (character) => character.toUpperCase());
}
