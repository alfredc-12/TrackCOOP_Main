function report(
  key: string,
  name: string,
  category: ReportDefinition["category"],
  description: string,
  dataSource: string,
  filters: ReportDefinition["filters"],
  roles: ReportDefinition["allowedRoles"] = [...staffRoles],
): ReportDefinition {
  return {
    key,
    name,
    category,
    description,
    dataSource,
    filters,
    allowedRoles: roles,
  };
}

